"""Offline review pages and comparison reports for the improvement workflow."""
import json
import shlex
from .cli_provider import BOUNDARY
from .improve import (ImproveStore, guard_directory, load_bundle, fingerprint, _read,
                      write_text, verify_original)


LIMITATION = ('M1 evaluates self-contained text responses only. Tool-dependent and companion-file '
              'skills are unsupported. A small model-generated suite and model judgments provide '
              'observations, not statistical or general superiority evidence.')
# At most twelve rows combine bounded responses/judgments; JSON escaping can triple bytes.
COMPARISON_BYTES = 64 * 1024 * 1024


def evaluation_markdown(evaluation, approval_hash):
    lines = ['# Review the evaluation before improvement', '',
             '`evaluation.json` is the editable source. This Markdown is regenerated by report.',
             '', 'Approval bundle SHA256: `' + approval_hash + '`', '',
             '## Purpose', '', evaluation['purpose'], '', '## Scope', '',
             evaluation['execution_scope'], evaluation['unsupported_reason'], '', LIMITATION,
             '', '## Fixed constraints', '']
    lines += ['- ' + item for item in evaluation['constraints']]
    lines += ['', '## Binary criteria', '']
    lines += ['- ' + c['id'] + (' (required)' if c['required'] else '') + ': ' + c['description']
              for c in evaluation['criteria']]
    for split in ('development', 'heldout'):
        lines += ['', '## ' + split, '']
        for case in evaluation[split]:
            lines += ['### ' + case['id'] + ' / ' + case['group_id'], '', case['prompt'], '']
    return '\n'.join(lines) + '\n'


def report_locked(store):
    manifest_path = store.path / 'manifest.json'
    manifest = _read(manifest_path)
    if not isinstance(manifest, dict):
        raise ValueError('invalid improvement manifest')
    # A failed prepare may not have produced a reviewable evaluation yet.
    if not (store.path / 'evaluation.json').exists():
        if manifest.get('kind') != 'skill-improvement' or manifest.get('schema_version') != 1:
            raise ValueError('not a supported skill-improvement directory')
        return {'state': manifest.get('state'), 'status': 'incomplete', 'complete': False,
                'reason': manifest.get('reason', 'evaluation_not_recorded'), 'directory': str(store.path),
                'next_step': 'Start improve prepare in a new output directory.'}
    manifest, bundle = load_bundle(store.path)
    approval_hash = fingerprint(bundle)
    warnings = []
    try:
        verify_original(bundle)
    except ValueError:
        warnings.append('Original source is unavailable or changed; a new prepare is required before run.')
    approved = store.path / 'approved.json'
    if approved.exists() and fingerprint(_read(approved)) != approval_hash:
        warnings.append('Editable inputs differ from the approved snapshot; running again requires a new prepare.')
    write_text(store, 'evaluation.md', evaluation_markdown(bundle['evaluation'], approval_hash))
    comparison_path = store.path / 'comparison.json'
    comparison = _read(comparison_path, limit=COMPARISON_BYTES) if comparison_path.exists() else None
    if comparison and manifest['state'] != 'completed' and comparison.get('complete') is not False:
        # Interrupted between saving comparison.json and recording completion.
        warnings.append('comparison.json was saved but completion was not recorded; its results are not reported.')
        comparison = None
    events = store.events()
    starts = {e['call_id'] for e in events if e['kind'] == 'call_started'}
    finishes = {e['call_id'] for e in events if e['kind'] == 'call_finished'}
    unresolved = sorted(starts - finishes)
    usage = [e.get('observed_usage') for e in events if e['kind'] == 'call_finished']
    effective_status = (comparison['status'] if comparison and manifest['state'] == 'completed' else
                        ('incomplete' if manifest['state'] in ('running', 'incomplete', 'preparing') else manifest['state']))
    summary = {'kind': 'skill-improvement', 'state': manifest['state'],
               'status': effective_status,
               'complete': manifest['state'] in ('draft', 'completed'),
               'unsupported': manifest['state'] == 'unsupported',
               'scope': bundle['evaluation']['execution_scope'], 'limitation': LIMITATION,
               'execution_boundary': BOUNDARY, 'directory': str(store.path),
               'approval_hash': approval_hash, 'evaluation': str(store.path / 'evaluation.md'),
               'source_path': bundle['source_path'],
               'provider': bundle['provider_profile']['provider'], 'model': bundle['provider_profile']['model'],
               'cli_version': bundle['provider_profile']['cli_version'],
               'model_identity': bundle['model_identity'], 'limits': bundle['limits'],
               'calls_started': len(starts), 'unresolved_calls': unresolved,
               'observed_usage': usage, 'cost_usd': None, 'warnings': warnings}
    if bundle['provider_profile'].get('version_tested') is False:
        warnings.append('CLI version ' + bundle['provider_profile']['cli_version']
                        + ' is untested; it was allowed with --allow-untested-cli.')
    if bundle['model_identity'] == 'requested_only':
        warnings.append('Model identity is pinned by the explicit selector only; server-side identity is unverified.')
    if comparison:
        summary['comparison'] = comparison
        summary['required_criteria'] = sorted(c['id'] for c in bundle['evaluation']['criteria'] if c['required'])
        summary['revision_selected'] = comparison.get('search_best_id', bundle['original_hash']) != bundle['original_hash']
        summary['comparison_path'] = str(comparison_path)
        summary['candidate_path'] = str(store.path / 'candidate' / 'SKILL.md') if manifest['state'] == 'completed' else None
    if summary['unsupported']:
        summary['reason'] = bundle['evaluation']['unsupported_reason']
        summary['next_step'] = 'Choose a self-contained text skill or decide the additional tool-execution scope.'
    elif manifest['state'] == 'draft':
        summary['next_step'] = ('Review evaluation.md (edit evaluation.json, then run improve report again), then: '
                                'skill-evolver improve run ' + shlex.quote(str(store.path))
                                + ' (asks for confirmation; non-interactive: add --approve-evaluation '
                                + approval_hash + ')')
    elif manifest['state'] == 'completed':
        summary['next_step'] = 'Review comparison.md and candidate/SKILL.md before adopting any change.'
    else:
        summary['reason'] = manifest.get('reason', 'prior_execution_not_reissued')
        summary['next_step'] = 'Execution is not retried. Read the report and start prepare in a new directory.'
    lines = ['# Skill improvement comparison', '', 'State: ' + summary['state'],
             'Result: ' + summary['status'], '', LIMITATION, '', BOUNDARY, '',
             'The original skill is not overwritten. Adoption is a separate user decision.', '',
             'CLI: ' + summary['provider'] + ' ' + summary['cli_version'] + ' / ' + summary['model'],
             'Model identity: ' + str(summary['model_identity']),
             'Calls started: ' + str(len(starts)),
             'Token usage is observed when reported; exact token/cost/subscription limits are not guaranteed.',
             '', '## Next step', '', summary['next_step'], '', '## Warnings', '']
    lines += ['- ' + item for item in warnings]
    if comparison:
        lines += ['', '## Fixed-suite results', '', '```json', json.dumps(comparison, ensure_ascii=False, indent=2), '```']
        if manifest['state'] == 'completed':
            record = _read(store.path / 'candidates' / (comparison['recommended_id'] + '.json'))
            lines += ['', '## Recommended candidate diff', '', '```diff', record['diff'], '```']
    write_text(store, 'comparison.md', '\n'.join(lines) + '\n')
    return summary


def report(directory):
    store = ImproveStore(guard_directory(directory))
    with store.lock():
        return report_locked(store)
